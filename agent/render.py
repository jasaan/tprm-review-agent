"""Render a validated Review as a Markdown report (follows references/report-template.md)."""

from __future__ import annotations

import re

from schema import Review

OUTCOME_LABEL = {
    "approve": "Approve",
    "approve_with_conditions": "Approve with conditions",
    "escalate": "Escalate",
    "reject": "Reject",
}
STATUS_LABEL = {
    "met": "Met",
    "partially_met": "Partially met",
    "not_met": "Not met",
    "not_evidenced": "Not evidenced",
}
RESOLUTION_LABEL = {"accepted": "Accepted", "rejected": "Rejected", "needs_answer": "Needs an answer"}
RESOLUTION_TARGET = {"intake": "Requesting team", "vendor": "Vendor", "review": "Draft review"}
SEVERITY_ORDER = {"critical": 0, "high": 1, "medium": 2, "low": 3}


NEXT_STEP = {
    "approve": "Approve, and track the remaining findings to closure.",
    "approve_with_conditions": "Approve once the vendor commits to the conditions below.",
    "escalate": "A named risk owner must decide whether to accept the risk or reject the vendor.",
    "reject": "Do not proceed: a mandatory requirement can't be met.",
}
_NUMBERED = re.compile(r"^\s*\d+[.)]\s+")


def severity_counts(r: Review) -> str:
    parts = [f"{n} {sev}" for sev in ("critical", "high", "medium", "low")
             if (n := sum(f.severity == sev for f in r.findings))]
    return (", ".join(parts[:-1]) + " and " + parts[-1] if len(parts) > 1 else parts[0]) + " findings" if parts else "no findings"


def split_conditions(items: list[str]) -> tuple[str, list[str]]:
    """Strip any numbering the model added; treat an unnumbered first item before numbered ones as an intro."""
    intro = ""
    if len(items) > 1 and not _NUMBERED.match(items[0]) and all(_NUMBERED.match(c) for c in items[1:]):
        intro, items = items[0], items[1:]
    return intro, [_NUMBERED.sub("", c).strip() for c in items]


def shorten(text: str, limit: int = 150) -> str:
    """First sentence, cut at a word boundary if it's still long."""
    sentences = re.split(r"(?<=[.;])\s", text)
    first = sentences[0]
    for more in sentences[1:]:
        if len(first) >= 60:
            break
        first = f"{first} {more}"  # a very short lead sentence needs the next one for context
    if len(first) <= limit:
        return first
    return first[:limit].rsplit(" ", 1)[0].rstrip(",;:") + "…"


def _cell(text: str) -> str:
    """Make text safe for a Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ").strip()


def _list(items: list[str]) -> str:
    return ", ".join(items) if items else "—"


def render(r: Review) -> str:
    out: list[str] = []
    add = out.append

    add(f"# Vendor security review: {r.vendor_name} — {r.product_or_service}\n")
    add(
        f"**Review date:** {r.review_date}  **Tier:** {r.inherent_risk.tier}  "
        f"**Outcome:** {OUTCOME_LABEL[r.outcome]}  **Next review:** {r.next_review_months} months\n"
    )
    add("> First-pass review generated by an AI agent from the documents listed below. "
        "A human risk owner makes the decision.\n")

    # Recommendation up front: the decision, the reasons, and what it takes to proceed.
    drivers = [f for f in sorted(r.findings, key=lambda f: SEVERITY_ORDER[f.severity])
               if f.severity in ("critical", "high")]
    intro, conditions = split_conditions(r.conditions)
    open_team = len(r.questions_for_requesting_team)
    add("## Recommendation\n")
    add(f"> **{OUTCOME_LABEL[r.outcome].upper()}:** {r.inherent_risk.tier} vendor with "
        f"{severity_counts(r)}. {NEXT_STEP[r.outcome]}")
    add(">")
    if drivers:
        add("> **Driving this decision:**")
        for f in drivers[:5]:
            add(f"> - **{f.severity.title()}:** {f.title}")
        if len(drivers) > 5:
            add(f"> - plus {len(drivers) - 5} more high findings (see Findings)")
        add(">")
    if conditions:
        add("> **To proceed** (full text under Conditions):")
        for i, c in enumerate(conditions, 1):
            add(f"> {i}. {shorten(c)}")
        add(">")
    add(f"> **Open questions:** {len(r.follow_up_questions)} for the vendor, {open_team} for the requesting team.  ")
    add(f"> **Next review:** {r.next_review_months} months.\n")

    add("## Summary\n")
    add(r.summary + "\n")

    ir = r.inherent_risk
    add("## Inherent risk\n")
    add(f"- **Data:** {_list(ir.data_types)}")
    add(f"- **Access:** {ir.access_level}")
    add(f"- **Criticality:** {ir.criticality}")
    add(f"- **Tier rationale:** {ir.rationale}\n")

    add("## Evidence reviewed\n")
    for d in r.documents_reviewed:
        add(f"- {d}")
    add("")

    s = r.soc2
    add("## SOC 2 summary\n")
    if not s.present:
        add("No SOC 2 report was provided.\n")
    else:
        add(f"- **Type / period:** {s.report_type}, {s.period}")
        add(f"- **Opinion:** {s.opinion}")
        add(f"- **Purchased product in scope:** {'Yes' if s.purchased_product_in_scope else '**No**'}")
        add(f"- **Scope notes:** {s.scope_notes}")
        add(f"- **Exceptions:** {_list(s.exceptions)}")
        add(f"- **Subservice organizations:** {_list(s.subservice_orgs)}")
        add(f"- **Customer controls we must operate (CUECs):** {_list(s.cuecs)}")
        add(f"- **Bridge letter needed:** {'Yes' if s.bridge_letter_needed else 'No'}\n")

    add("## Control assessment\n")
    add("| Domain | Status | Evidence | NIST CSF 2.0 | NIST 800-53 | ISO 27001 |")
    add("|---|---|---|---|---|---|")
    for c in r.controls:
        add(
            f"| {_cell(c.domain)} | {STATUS_LABEL[c.status]} | {_cell(c.evidence)} | "
            f"{_list(c.nist_csf)} | {_list(c.nist_800_53)} | {_list(c.iso_27001)} |"
        )
    add("")

    findings = sorted(r.findings, key=lambda f: SEVERITY_ORDER[f.severity])
    add("## Findings\n")
    if not findings:
        add("No findings.\n")
    else:
        add("| ID | Severity | Title | Due (days) |")
        add("|---|---|---|---|")
        for f in findings:
            add(f"| {f.id} | {f.severity.title()} | {_cell(f.title)} | {f.remediation_due_days} |")
        add("")
        for f in findings:
            add(f"### {f.id}: {f.title} ({f.severity})\n")
            add(f"- **Domain:** {f.domain}")
            add(f"- **What's wrong:** {f.description}")
            add(f"- **Evidence:** {f.evidence} (sources: {_list(f.source_documents)})")
            add(f"- **Recommendation:** {f.recommendation}\n")

    add("## Contradictions between claims and evidence\n")
    if not r.contradictions:
        add("None found.\n")
    else:
        add("| Claim (source) | Contradicting evidence (source) |")
        add("|---|---|")
        for x in r.contradictions:
            add(f"| {_cell(x.claim)} ({_cell(x.claim_source)}) | "
                f"{_cell(x.contradicting_evidence)} ({_cell(x.evidence_source)}) |")
        add("")


    add("## Outcome rationale\n")
    add(r.outcome_rationale + "\n")
    if conditions:
        add("### Conditions\n")
        if intro:
            add(intro + "\n")
        for i, c in enumerate(conditions, 1):
            add(f"{i}. {c}")
        add("")

    add("## Follow-up questions for the vendor\n")
    for i, q in enumerate(r.follow_up_questions, 1):
        add(f"{i}. {q}")
    add("")

    if r.questions_for_requesting_team:
        add("## Questions for the requesting team\n")
        for i, q in enumerate(r.questions_for_requesting_team, 1):
            add(f"{i}. {q}")
        add("")

    add("## Challenge log\n")
    if not r.challenge_log:
        add("No challenges were raised.\n")
    else:
        add("A separate skeptic step challenged the requesting team's intake, the vendor's answers and "
            "the draft review. Each challenge and how it was resolved:\n")
        add("| ID | Target | Challenge | Resolution | Response |")
        add("|---|---|---|---|---|")
        for c in r.challenge_log:
            add(f"| {c.challenge_id} | {RESOLUTION_TARGET[c.target]} | {_cell(c.challenge)} | "
                f"{RESOLUTION_LABEL[c.resolution]} | {_cell(c.response)} |")
        add("")

    add("## Limitations\n")
    for item in r.limitations or ["None noted."]:
        add(f"- {item}")
    add("")

    return "\n".join(out)
